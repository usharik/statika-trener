export type Lang = 'cs' | 'ru';
export type TKey = keyof Dict;
export const dicts: Record<Lang, Dict> = { cs, ru };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: Vars): string {
  let s = dicts[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const LangContext = createContext<Lang>('cs');

export function useT() {
  const lang = useContext(LangContext);
  return (key: TKey, vars?: Vars) => translate(lang, key, vars);
}

export const useLang = () => useContext(LangContext);
